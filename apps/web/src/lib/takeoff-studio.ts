export type StudioQuantityRow = {
  classificationId: string;
  name: string;
  kind: StudioClassKind;
  colour: string;
  quantity: number;
  unit: string;
  pieces: number;
};

export function summariseStudioQuantities(studio: StudioState): StudioQuantityRow[] {
  return studio.classifications.map((cls) => {
    const items = studio.geometries.filter((geo) => geo.classificationId === cls.id);
    let quantity = 0;
    for (const geo of items) {
      const scale = scaleForPage(studio, geo.documentId, geo.page);
      const mpu = scale?.metresPerUnit || 0;
      if (geo.kind === "count") {
        quantity += 1;
      } else if (geo.kind === "linear") {
        quantity += linearMeasuredMetresForGeo(geo.points, mpu, geo);
      } else if (geo.kind === "area" && geo.closed) {
        quantity += polygonArea(geo.points) * mpu * mpu;
      }
    }
    return {
      classificationId: cls.id,
      name: cls.name,
      kind: cls.kind,
      colour: cls.colour,
      quantity: cls.kind === "count" ? quantity : Number(quantity.toFixed(2)),
      unit: cls.unit,
      pieces: items.length,
    };
  });
}

export function studioQuantitiesToMaterialAllowances(
  studio: StudioState,
  projectId: string,
): Array<{
  id: string;
  section: string;
  description: string;
  quantity: number;
  unit: string;
  unitCost: number;
  markupPercent: number;
  supplierRequired: boolean;
}> {
  const sizedLinearIds = new Set(
    studio.geometries
      .filter((geo) => geo.kind === "linear" && (geo.material || geo.diameter))
      .map((geo) => geo.classificationId),
  );
  const fittingClassIds = new Set(["cls-fit-90-elbow", "cls-fit-coupling"]);
  return summariseStudioQuantities(studio)
    .filter((row) => row.quantity > 0)
    .filter((row) => !sizedLinearIds.has(row.classificationId) && !fittingClassIds.has(row.classificationId))
    .map((row) => ({
      id: `studio-mat-${projectId}-${row.classificationId}`,
      section: row.kind === "area" ? "Areas" : row.kind === "linear" ? "Linears" : "Counts",
      description: `Takeoff · ${row.name}`,
      quantity: row.quantity,
      unit: row.unit,
      unitCost: 0,
      markupPercent: 0,
      supplierRequired: false,
    }));
}

/** Import skill text-tag count pins onto the Studio canvas as Count classifications. */
export function importSkillCountsIntoStudio(
  studio: StudioState,
  measured: Array<{
    id: string;
    assemblyId?: string;
    kind: "primary" | "secondary";
    code: string;
    description: string;
    quantity?: number;
    unit: string;
    method?: string;
    confidence?: TakeoffConfidence;
    sourceSheetIds?: string[];
    tagMatches?: Array<{
      id: string;
      documentId: string;
      fileName?: string;
      pageNumber: number;
      text?: string;
      x: number;
      y: number;
      pageWidth?: number;
      pageHeight?: number;
      excluded?: boolean;
      manual?: boolean;
      derived?: boolean;
    }>;
  }>,
  options?: {
    canvasWidth?: number;
    canvasHeight?: number;
    replaceExistingAi?: boolean;
    aiReviewStatus?: StudioAiReviewStatus;
  },
): StudioState {
  const canvasW = options?.canvasWidth || 0;
  // Only replace measured AI count pins — keep pipe runs, fittings, and propose-* plant pins.
  const keep = options?.replaceExistingAi
    ? studio.geometries.filter((geo) => {
      if (geo.kind !== "count" || geo.autoGenerated) return true;
      if (!isAiStudioGeometry(geo)) return true;
      if (geo.id.startsWith("ai-propose-")) return true;
      return false;
    })
    : studio.geometries;

  const classifications = [...studio.classifications];
  const geometries = [...keep];

  for (const row of measured) {
    if (row.kind !== "primary" || row.unit !== "nr") continue;
    const matches = (row.tagMatches || []).filter((match) => !match.excluded);
    if (!matches.length) continue;

    let cls = classifications.find((item) => item.id === `cls-ai-${row.code}`);
    if (!cls) {
      cls = {
        id: `cls-ai-${row.code}`,
        kind: "count",
        name: row.description || row.code,
        colour: nextClassificationColour(classifications),
        unit: "nr",
        notes: `Imported from Blake · ${row.code}`,
      };
      classifications.push(cls);
    }

    for (const match of matches) {
      const pageHeight = match.pageHeight || 0;
      const renderScale =
        canvasW && match.pageWidth ? canvasW / match.pageWidth : 1.35;
      // PDF text transforms are origin bottom-left; Studio canvas is top-left at render scale.
      geometries.push({
        id: `ai-${match.id}`,
        classificationId: cls.id,
        kind: "count",
        documentId: match.documentId,
        page: match.pageNumber || 1,
        source: "ai",
        confidence: row.confidence,
        reviewStatus: options?.aiReviewStatus ?? studio.aiReviewStatus ?? "pending",
        sourceTagId: match.id,
        sourceText: match.text,
        point: {
          x: match.x * renderScale,
          y: pageHeight ? (pageHeight - match.y) * renderScale : match.y * renderScale,
        },
      });
    }
  }

  const firstAi = geometries.find((geo) => geo.id.startsWith("ai-"));
  const firstAiClass = classifications.find((c) => c.id.startsWith("cls-ai-"));

  return {
    ...studio,
    classifications,
    geometries,
    activeDocumentId: firstAi?.documentId || studio.activeDocumentId,
    activePage: firstAi?.page || studio.activePage,
    activeClassificationId: firstAiClass?.id || studio.activeClassificationId,
    tool: "select",
    aiReviewStatus: options?.aiReviewStatus ?? studio.aiReviewStatus,
    aiReviewMeasured: studio.aiReviewMeasured,
    aiReviewUpdatedAt: studio.aiReviewUpdatedAt,
    updatedAt: new Date().toISOString(),
  };
}
