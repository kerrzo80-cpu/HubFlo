export function polylineLength(points: StudioPoint[]): number {
  let total = 0;
  for (let i = 1; i < points.length; i += 1) {
    const a = points[i - 1];
    const b = points[i];
    if (!a || !b) continue;
    total += Math.hypot(b.x - a.x, b.y - a.y);
  }
  return total;
}

/** Clamp vertical extra metres — never negative. */
export function clampRiseDropM(value?: number | null): number {
  if (value == null || !Number.isFinite(value)) return 0;
  return Math.max(0, value);
}

/** Clamp drop count to a non-negative integer. */
export function clampDropCount(value?: number | null): number {
  if (value == null || !Number.isFinite(value)) return 0;
  return Math.max(0, Math.floor(value));
}

export type LinearDropFields = {
  riseDropM?: number | null;
  dropCount?: number | null;
  dropHeightM?: number | null;
};

export type ResolvedLinearDrop = {
  /** Effective count for UI / elbows (legacy bare riseDropM → 1). */
  dropCount: number;
  /** Height per drop (legacy bare riseDropM → that total). */
  dropHeightM: number;
  /** Vertical metres added to plan length. */
  verticalM: number;
  /** Elbows at ceiling–wall junctions (one per drop). */
  elbowCount: number;
  /**
   * BoQ fragment without outer parens, e.g. `3 × 2.4 m drops` or `2.4 m drop`.
   * Empty when no vertical.
   */
  noteLabel: string;
  /** `drops` = N×H source of truth; `total` = riseDropM override; `none`. */
  mode: "drops" | "total" | "none";
};

function formatDropMetres(value: number): string {
  const rounded = Number(value.toFixed(1));
  return Number.isInteger(rounded) ? String(rounded) : String(rounded);
}

/** Keep N×H totals tidy (e.g. 3×2.4 → 7.2, not 7.199…'). */
export function roundDropMetres(value: number): number {
  return Math.round(value * 1000) / 1000;
}

/**
 * Resolve vertical metres for a Length run.
 * - dropCount > 0 → vertical = count × height (source of truth)
 * - dropCount === 0 with explicit count fields → riseDropM total override
 * - legacy only riseDropM → treat as 1 × height for display / elbows / metres
 */
export function resolveLinearDrop(fields: LinearDropFields): ResolvedLinearDrop {
  const hasCountFields = fields.dropCount != null || fields.dropHeightM != null;
  const count = clampDropCount(fields.dropCount);
  const height = clampRiseDropM(fields.dropHeightM);
  const total = clampRiseDropM(fields.riseDropM);

  if (hasCountFields) {
    if (count > 0) {
      const verticalM = roundDropMetres(count * height);
      if (!(verticalM > 0)) {
        return {
          dropCount: count,
          dropHeightM: height,
          verticalM: 0,
          elbowCount: 0,
          noteLabel: "",
          mode: "none",
        };
      }
      const noteLabel = count === 1
        ? `${formatDropMetres(height)} m drop`
        : `${count} × ${formatDropMetres(height)} m drops`;
      return {
        dropCount: count,
        dropHeightM: height,
        verticalM,
        elbowCount: count,
        noteLabel,
        mode: "drops",
      };
    }
    // count === 0 → optional total override
    if (total > 0) {
      return {
        dropCount: 0,
        dropHeightM: height,
        verticalM: total,
        elbowCount: 1,
        noteLabel: `${formatDropMetres(total)} m drop`,
        mode: "total",
      };
    }
    return {
      dropCount: 0,
      dropHeightM: height,
      verticalM: 0,
      elbowCount: 0,
      noteLabel: "",
      mode: "none",
    };
  }

  // Legacy: only riseDropM stored → migrate as 1 × height when loading/resolving
  if (total > 0) {
    return {
      dropCount: 1,
      dropHeightM: total,
      verticalM: total,
      elbowCount: 1,
      noteLabel: `${formatDropMetres(total)} m drop`,
      mode: "drops",
    };
  }
  return {
    dropCount: 0,
    dropHeightM: 0,
    verticalM: 0,
    elbowCount: 0,
    noteLabel: "",
    mode: "none",
  };
}

/** Normalise persisted fields: sync riseDropM; migrate bare riseDropM → count/height. */
export function syncLinearDropFields<T extends LinearDropFields>(fields: T): T & {
  dropCount: number;
  dropHeightM: number;
  riseDropM: number;
} {
  const resolved = resolveLinearDrop(fields);
  if (fields.dropCount != null || fields.dropHeightM != null) {
    const count = clampDropCount(fields.dropCount);
    const height = clampRiseDropM(fields.dropHeightM);
    const riseDropM = count > 0
      ? roundDropMetres(count * height)
      : clampRiseDropM(fields.riseDropM);
    return { ...fields, dropCount: count, dropHeightM: height, riseDropM };
  }
  // Migrate legacy
  if (resolved.verticalM > 0) {
    return {
      ...fields,
      dropCount: 1,
      dropHeightM: resolved.verticalM,
      riseDropM: resolved.verticalM,
    };
  }
  return { ...fields, dropCount: 0, dropHeightM: 0, riseDropM: 0 };
}

/**
 * Measured pipe metres for a Length run: plan polyline × scale + rise/drop.
 * Rise/drop alone still counts when scale is missing (absolute metres).
 */
export function linearMeasuredMetres(
  points: StudioPoint[],
  metresPerUnit: number,
  riseDropM?: number | null,
): number {
  const planM = metresPerUnit > 0 ? polylineLength(points) * metresPerUnit : 0;
  return Math.max(0, planM + clampRiseDropM(riseDropM));
}

/** Plan × scale + resolved vertical (count×height or total override / legacy). */
export function linearMeasuredMetresForGeo(
  points: StudioPoint[],
  metresPerUnit: number,
  fields: LinearDropFields,
): number {
  return linearMeasuredMetres(points, metresPerUnit, resolveLinearDrop(fields).verticalM);
}

/** Shoelace area in page units². */
export function polygonArea(points: StudioPoint[]): number {
  if (points.length < 3) return 0;
  let sum = 0;
  for (let i = 0; i < points.length; i += 1) {
    const a = points[i];
    const b = points[(i + 1) % points.length];
    if (!a || !b) continue;
    sum += a.x * b.y - b.x * a.y;
  }
  return Math.abs(sum) / 2;
}

export function scaleForPage(studio: StudioState, documentId: string, page: number): StudioPageScale | undefined {
  return studio.scales.find((row) => row.documentId === documentId && row.page === page);
}

/** Prefer existing calibrated scales; fill gaps from `incoming` without wiping user calibration. */
export function mergeStudioScales(
  preferred: StudioPageScale[],
  incoming: StudioPageScale[],
): StudioPageScale[] {
  const byKey = new Map<string, StudioPageScale>();
  const keyOf = (row: StudioPageScale) => `${row.documentId}::${row.page}`;
  for (const row of incoming) {
    if (!(row.metresPerUnit > 0)) continue;
    byKey.set(keyOf(row), row);
  }
  for (const row of preferred) {
    if (!(row.metresPerUnit > 0)) continue;
    const key = keyOf(row);
    const existing = byKey.get(key);
    // Prefer two-point / knownMetres user calibrations over sheet-ratio hints.
    if (!existing || row.knownMetres || row.calibrateFrom || !existing.knownMetres) {
      byKey.set(key, row);
    }
  }
  return [...byKey.values()];
}

/**
 * When a drawing has scale on one page, copy metresPerUnit to sibling pages that
 * already have mark-up / Blake runs but no scale yet (drawing-level expectation).
 */
export function fillMissingPageScalesFromDocument(studio: StudioState): StudioState {
  const scales = [...studio.scales];
  const byDoc = new Map<string, StudioPageScale[]>();
  for (const row of scales) {
    if (!(row.metresPerUnit > 0)) continue;
    const list = byDoc.get(row.documentId) || [];
    list.push(row);
    byDoc.set(row.documentId, list);
  }
  if (!byDoc.size) return studio;

  const pagesNeeding = new Map<string, Set<number>>();
  for (const geo of studio.geometries) {
    if (geo.kind !== "linear" && geo.kind !== "area") continue;
    const set = pagesNeeding.get(geo.documentId) || new Set<number>();
    set.add(geo.page);
    pagesNeeding.set(geo.documentId, set);
  }
  // Always include any page that already has an explicit scale source page's siblings
  // for documents the user calibrated, even before mark-up exists.
  for (const [documentId, rows] of byDoc) {
    const set = pagesNeeding.get(documentId) || new Set<number>();
    for (const row of rows) set.add(row.page);
    pagesNeeding.set(documentId, set);
  }

  let changed = false;
  for (const [documentId, pages] of pagesNeeding) {
    const sources = byDoc.get(documentId);
    if (!sources?.length) continue;
    const preferred =
      sources.find((row) => row.knownMetres || row.calibrateFrom) ||
      sources.find((row) => Boolean(row.label)) ||
      sources[0];
    if (!preferred) continue;
    for (const page of pages) {
      const exists = scales.some((row) => row.documentId === documentId && row.page === page && row.metresPerUnit > 0);
      if (exists) continue;
      scales.push({
        documentId,
        page,
        metresPerUnit: preferred.metresPerUnit,
        label: preferred.label || (preferred.knownMetres ? `${preferred.knownMetres} m` : undefined),
      });
      changed = true;
    }
  }
  if (!changed) return studio;
  return { ...studio, scales, updatedAt: new Date().toISOString() };
}

/** Upsert one page scale; optionally copy metres to other pages of the same drawing that lack scale. */
export function upsertStudioPageScale(
  studio: StudioState,
  scale: StudioPageScale,
  options?: { applyToDocumentPages?: boolean },
): StudioState {
  const nextScales = [
    ...studio.scales.filter((row) => !(row.documentId === scale.documentId && row.page === scale.page)),
    scale,
  ];
  let next: StudioState = { ...studio, scales: nextScales, updatedAt: new Date().toISOString() };
  if (options?.applyToDocumentPages !== false) {
    next = fillMissingPageScalesFromDocument(next);
  }
  return next;
}

export function isAiStudioGeometry(geo: StudioGeometry): boolean {
  // Explicit manual accept/edit wins over ai-* id prefixes from Blake/vision.
  if (geo.source === "manual") return false;
  return geo.source === "ai" || geo.id.startsWith("ai-");
}

export function studioHasAiCounts(studio: StudioState): boolean {
  return studio.geometries.some((geo) => geo.kind === "count" && isAiStudioGeometry(geo))
    || Boolean(studio.aiReviewMeasured?.some((row) =>
      (row.tagMatches || []).some((match) => !match.excluded),
    ));
}

export function studioHasAiPipeRuns(studio: StudioState): boolean {
  return studio.geometries.some((geo) => geo.kind === "linear" && isAiStudioGeometry(geo));
}

/** Ensure preset coloured pipe/service classes exist (Hot/Cold/Heating/Waste…). Does not overwrite user colour edits. */
export function ensureServiceClassifications(studio: StudioState): StudioState {
  const classifications = [...studio.classifications];
  let changed = false;
  for (const def of SERVICE_CLASS_DEFS) {
    const idx = classifications.findIndex((cls) => cls.id === def.id);
    if (idx < 0) {
      const { role: _role, ...cls } = def;
      classifications.push(cls);
      changed = true;
      continue;
    }
    const existing = classifications[idx]!;
    let next = existing;
    // Backfill layer on older projects without changing colour the user may have edited.
    if (!existing.layer && def.layer) {
      next = { ...next, layer: def.layer };
    }
    // Migrate Blake's old green "cold" swatch to standard plumbing blue (only exact prior default).
    if (def.id === "cls-ai-P-PIPE-C" && existing.colour.toLowerCase() === "#1f8f5f") {
      next = { ...next, colour: def.colour };
    }
    if (next !== existing) {
      classifications[idx] = next;
      changed = true;
    }
  }
  if (!changed) return studio;
  return { ...studio, classifications, updatedAt: new Date().toISOString() };
}

/** @deprecated alias — Blake pipe import path */
export function ensurePipeRunClassifications(studio: StudioState): StudioState {
  return ensureServiceClassifications(studio);
}

export function classificationLayer(cls: StudioClassification): StudioServiceLayerId {
  return cls.layer || "general";
}

export function setStudioActiveLayer(
  studio: StudioState,
  layerId: StudioServiceLayerId | "all",
): StudioState {
  const next = ensureServiceClassifications(studio);
  if (layerId === "all") {
    return { ...next, activeLayerId: "all", updatedAt: new Date().toISOString() };
  }
  const inLayer = next.classifications.filter((cls) => classificationLayer(cls) === layerId);
  const keepActive = inLayer.some((cls) => cls.id === next.activeClassificationId);
  const preferred =
    inLayer.find((cls) => cls.kind === "linear")
    || inLayer[0]
    || next.classifications.find((cls) => cls.id === next.activeClassificationId);
  return {
    ...next,
    activeLayerId: layerId,
    activeClassificationId: keepActive ? next.activeClassificationId : preferred?.id,
    tool: preferred?.kind || next.tool,
    updatedAt: new Date().toISOString(),
  };
}

export function setClassificationColour(
  studio: StudioState,
  classificationId: string,
  colour: string,
): StudioState {
  const nextColour = /^#?[0-9a-fA-F]{6}$/.test(colour.trim())
    ? (colour.startsWith("#") ? colour : `#${colour}`)
    : null;
  if (!nextColour) return studio;
  return {
    ...studio,
    classifications: studio.classifications.map((cls) =>
      cls.id === classificationId ? { ...cls, colour: nextColour } : cls,
    ),
    updatedAt: new Date().toISOString(),
  };
}

/** Apply the first scale ratio hint found in drawing text to every page that lacks a scale. */
export function applyScaleHintsToStudio(
  studio: StudioState,
  pages: Array<{ documentId: string; pageNumber: number; fullText?: string }>,
  renderScale = 1.35,
): { studio: StudioState; appliedLabel: string | null } {
  let appliedLabel: string | null = null;
  let metresPerUnit: number | null = null;
  for (const page of pages) {
    const hints = detectScaleRatioHints(page.fullText || "");
    if (!hints[0]) continue;
    const denom = parseScaleRatioLabel(hints[0]);
    if (!denom) continue;
    metresPerUnit = metresPerUnitFromRatio(denom, renderScale);
    appliedLabel = hints[0];
    break;
  }
  if (!metresPerUnit || !appliedLabel) return { studio, appliedLabel: null };

  const scales = [...studio.scales];
  for (const page of pages) {
    const exists = scales.some((row) => row.documentId === page.documentId && row.page === page.pageNumber);
    if (exists) continue;
    scales.push({
      documentId: page.documentId,
      page: page.pageNumber,
      metresPerUnit,
      label: appliedLabel,
    });
  }
  return {
    studio: { ...studio, scales, updatedAt: new Date().toISOString() },
    appliedLabel,
  };
}

export function importPipeRunsIntoStudio(
  studio: StudioState,
  runs: Array<{
    documentId: string;
    pageNumber: number;
    points: StudioPoint[];
    role: "hot" | "cold" | "waste" | "other";
    pageHeight: number;
    colourHex?: string;
  }>,
  options?: {
    renderScale?: number;
    replaceExistingAiPipes?: boolean;
    aiReviewStatus?: StudioAiReviewStatus;
    /** Size Blake runs (e.g. cu-22) so BOQ + fittings resolve. */
    pipeSpec?: { id: string; material: string; diameter: string; stockLengthM: number };
    wastePipeSpec?: { id: string; material: string; diameter: string; stockLengthM: number };
  },
): StudioState {
  const renderScale = options?.renderScale ?? 1.35;
  let next = ensurePipeRunClassifications(studio);
  let keep = next.geometries;
  if (options?.replaceExistingAiPipes) {
    // Only wipe measured Blake pipes (ai-pipe-*), never design-propose stubs (ai-propose-*).
    const removedPipeIds = new Set(
      next.geometries
        .filter((geo) => geo.kind === "linear" && geo.id.startsWith("ai-pipe-"))
        .map((geo) => geo.id),
    );
    keep = next.geometries.filter((geo) => {
      if (geo.kind === "linear" && geo.id.startsWith("ai-pipe-")) return false;
      if (
        geo.kind === "count"
        && geo.autoGenerated
        && geo.linkedLinearId
        && removedPipeIds.has(geo.linkedLinearId)
      ) {
        return false;
      }
      return true;
    });
  }
  const geometries = [...keep];

  for (const [index, run] of runs.entries()) {
    if (run.role === "other" || run.points.length < 2) continue;
    const def = PIPE_CLASS_DEFS.find((row) => row.role === run.role);
    if (!def) continue;
    const points = run.points.map((point) => ({
      x: point.x * renderScale,
      y: (run.pageHeight - point.y) * renderScale,
    }));
    const sized = run.role === "waste" ? options?.wastePipeSpec : options?.pipeSpec;
    geometries.push({
      id: `ai-pipe-${run.documentId}-${run.pageNumber}-${index}`,
      classificationId: def.id,
      kind: "linear",
      documentId: run.documentId,
      page: run.pageNumber,
      points,
      source: "ai",
      confidence: "Medium",
      reviewStatus: options?.aiReviewStatus ?? "pending",
      notes: `Blake vector stroke · ${run.colourHex || run.role}`,
      material: sized?.material,
      diameter: sized?.diameter,
      stockLengthM: sized?.stockLengthM,
      pipeSpecId: sized?.id,
    });
  }

  const firstPipe = geometries.find((geo) => geo.kind === "linear" && isAiStudioGeometry(geo));
  return {
    ...next,
    geometries,
    activeDocumentId: firstPipe?.documentId || next.activeDocumentId,
    activePage: firstPipe?.page || next.activePage,
    activeClassificationId: firstPipe?.classificationId || next.activeClassificationId,
    tool: firstPipe ? "select" : next.tool,
    updatedAt: new Date().toISOString(),
  };
}

